-- 20261123150000_inventory_drop_price_amount.up.sql
-- Решение Павла 23.11.2026: в описи материального отдела цены и суммы не храним.
-- Причина: деньги в этом разделе не нужны, а любое хранение цен создаёт риск утечки
-- в бэкапы, дампы и логи. Значения удаляются безвозвратно; исходник — таблица Павла
-- и снимок бэкапа от 23.11.2026.
--
-- SQLite умеет DROP COLUMN с 3.35 (драйвер modernc v1.20.4 — новее), индексов и
-- внешних ключей на этих колонках нет, поэтому пересобирать таблицу не нужно.

ALTER TABLE inventory_numbers DROP COLUMN price;
ALTER TABLE inventory_numbers DROP COLUMN amount;

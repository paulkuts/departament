-- Время событий журнала ключей приводим к единому формату базы:
-- 'YYYY-MM-DD HH:MM:SS' в UTC (как CURRENT_TIMESTAMP в остальных журналах).
-- Раньше часть записей попала в базу в формате time.Time.String()
-- («2026-09-14 10:37:22.137563681 +0000 UTC m=+213...») — такие значения
-- браузер не разбирал, и в журнале время показывалось неверно.
UPDATE key_logs
   SET timestamp = substr(timestamp, 1, 19)
 WHERE timestamp LIKE '%+0000 UTC%';
